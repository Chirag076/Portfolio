/*
  Renders the four project illustrations (src/components/ProjectArt.jsx) to
  static SVG markup in src/generated/art.js, before the app is built.

  Why: the scenes are a few hundred SVG nodes each and appear several times
  on the landing page. As plain markup they cost React nothing to hydrate;
  as JSX they would be rebuilt node by node on every visit. Runs on plain
  Node with the Babel preset CRA already ships (`npm run build` and
  `npm start` call it automatically through the pre-scripts).
*/
const fs = require("fs");
const path = require("path");

process.env.NODE_ENV = "production";
process.env.BABEL_ENV = "production";

const root = path.resolve(__dirname, "..");
const src = path.join(root, "src");
const outDir = path.join(src, "generated");
const outFile = path.join(outDir, "art.js");

const babel = require("@babel/core");
const presetReactApp = require.resolve("babel-preset-react-app");
const compile = (module, filename) => {
  const code = fs.readFileSync(filename, "utf8");
  const out = babel.transformSync(code, {
    filename,
    babelrc: false,
    configFile: false,
    presets: [[presetReactApp, { runtime: "automatic" }]],
    sourceMaps: false,
  });
  module._compile(out.code, filename);
};
const originalJs = require.extensions[".js"];
require.extensions[".js"] = (module, filename) => {
  if (filename.startsWith(src)) return compile(module, filename);
  return originalJs(module, filename);
};
require.extensions[".jsx"] = compile;
require.extensions[".css"] = () => {};

/* the generated module must exist before ProjectArt can be required */
if (!fs.existsSync(outFile)) {
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, "export const ART_MARKUP = {};\n");
}

const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const { SCENES, ART_COLORS } = require(path.join(src, "components", "ProjectArt.jsx"));

const markup = {};
for (const kind of Object.keys(SCENES)) {
  const Scene = SCENES[kind];
  markup[kind] = renderToStaticMarkup(
    React.createElement(Scene, { id: `art-${kind}`, p: ART_COLORS[kind] }),
  );
}

const body =
  "/* Generated by scripts/art.js from src/components/ProjectArt.jsx — do not edit. */\n" +
  `export const ART_MARKUP = ${JSON.stringify(markup, null, 0)};\n`;

if (!fs.existsSync(outFile) || fs.readFileSync(outFile, "utf8") !== body) {
  fs.writeFileSync(outFile, body);
  console.log(`art: wrote ${Object.keys(markup).length} scenes to src/generated/art.js`);
} else {
  console.log("art: up to date");
}
